// Imagen de evento según categoría/severidad
export function getEventImage(category: string, _severity: string): string {
  switch (category) {
    case 'economic':
      return IMAGES.events.economicCrisis;
    case 'social':
      return IMAGES.events.socialProtest;
    case 'political':
      return IMAGES.events.corruption;
    case 'natural':
      return IMAGES.events.flood;
    case 'international':
      return IMAGES.events.infrastructure;
    default:
      return IMAGES.events.electionDay;
  }
}

// Retrato de asesor según especialidad
export function getAdvisorPortrait(specialty: string): string {
  const lower = specialty.toLowerCase();
  if (lower.includes('econom')) return IMAGES.advisors.economyMale;
  if (lower.includes('comunicaci')) return IMAGES.advisors.communicationFemale;
  if (lower.includes('infraestruc')) return IMAGES.advisors.institutionalFemale;
  if (lower.includes('social')) return IMAGES.advisors.socialFemale;
  if (lower.includes('internacion')) return IMAGES.advisors.foreignFemale;
  if (lower.includes('seguridad')) return IMAGES.advisors.securityFemale;
  if (lower.includes('educaci')) return IMAGES.advisors.socialEducationFemale;
  return IMAGES.advisors.economyMale;
}

import { THUMBNAIL_ARCHETYPES } from './iconThumbnails';

// Avatar de arquetipo
export function getArchetypeImage(archetype: string): string {
  return THUMBNAIL_ARCHETYPES[archetype] || THUMBNAIL_ARCHETYPES.politico;
}

// Fondo sugerido según cargo
export function getPositionBackground(position: string): string {
  switch (position) {
    case 'intendente':
      return IMAGES.backgrounds.municipalPlaza;
    case 'gobernador':
      return IMAGES.backgrounds.governmentGardens;
    case 'presidente':
      return IMAGES.backgrounds.congressSunrise;
    default:
      return IMAGES.backgrounds.congressSunset;
  }
}
